def get_optimizer(model):
    backbone_params, other_params = [], []
    for name, param in model.named_parameters():
        if 'visual_stream.backbone' in name:
            backbone_params.append(param)
        else:
            other_params.append(param)
    return optim.AdamW([
        {'params': backbone_params, 'lr': 1e-5},
        {'params': other_params,    'lr': 1e-4}
    ], weight_decay=0.01)


def train_one_epoch(model, loader, optimizer, criterion, scaler):
    model.train()
    correct, total, running_loss = 0, 0, 0.0
    loop = tqdm(loader, leave=False)
    for imgs, coords, labels in loop:
        imgs, coords, labels = imgs.to(device), coords.to(device), labels.to(device)
        optimizer.zero_grad()
        with torch.amp.autocast('cuda'):
            outputs = model(imgs, coords)
            loss    = criterion(outputs, labels)
        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()
        _, predicted = outputs.max(1)
        total        += labels.size(0)
        correct      += predicted.eq(labels).sum().item()
        running_loss += loss.item()
        loop.set_postfix(acc=f'{100.*correct/total:.1f}%', loss=f'{loss.item():.3f}')
    return 100.*correct/total, running_loss/len(loader)


@torch.no_grad()
def evaluate(model, loader):
    model.eval()
    correct, total = 0, 0
    all_preds, all_labels = [], []
    for imgs, coords, labels in loader:
        imgs, coords, labels = imgs.to(device), coords.to(device), labels.to(device)
        with torch.amp.autocast('cuda'):
            outputs = model(imgs, coords)
        _, predicted = outputs.max(1)
        total   += labels.size(0)
        correct += predicted.eq(labels).sum().item()
        all_preds.extend(predicted.cpu().numpy())
        all_labels.extend(labels.cpu().numpy())
    return 100.*correct/total, all_preds, all_labels


def train_model(model, train_loader, val_loader, model_name='model',
                epochs=20, patience=7):
    optimizer = get_optimizer(model)
    scheduler = optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=epochs, eta_min=1e-6
    )
    criterion = nn.CrossEntropyLoss(label_smoothing=0.05)
    scaler    = torch.amp.GradScaler('cuda')
    history   = {'train_acc':[], 'val_acc':[], 'train_loss':[]}
    best_val, best_state, pat = 0.0, None, 0

    print(f"\n{'='*60}")
    print(f'Training: {model_name} | {epochs} epochs | patience={patience}')
    print(f"{'='*60}")

    for epoch in range(epochs):
        tr_acc, tr_loss = train_one_epoch(model, train_loader, optimizer, criterion, scaler)
        vl_acc, _, _    = evaluate(model, val_loader)
        scheduler.step()
        history['train_acc'].append(tr_acc)
        history['val_acc'].append(vl_acc)
        history['train_loss'].append(tr_loss)
        lr = scheduler.get_last_lr()[0]
        print(f'Epoch {epoch+1:2d}/{epochs} | Train: {tr_acc:.2f}% '
              f'(loss={tr_loss:.3f}) | Val: {vl_acc:.2f}% | LR: {lr:.2e}')
        if vl_acc > best_val:
            best_val  = vl_acc
            best_state = copy.deepcopy(model.state_dict())
            torch.save(best_state, f'best_{model_name}.pth')
            print(f'  -> New best val: {best_val:.2f}% — saved.')
            pat = 0
        else:
            pat += 1
            if pat >= patience:
                print(f'  Early stopping at epoch {epoch+1}')
                break
    model.load_state_dict(best_state)
    return history, best_val


