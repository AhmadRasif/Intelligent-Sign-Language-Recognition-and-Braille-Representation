def plot_training_history(histories, model_names, save_path='training_curves.png'):
    fig, axes = plt.subplots(1, 2, figsize=(16, 6))
    colors = ['#2196F3', '#F44336', '#4CAF50']
    for i, (history, name) in enumerate(zip(histories, model_names)):
        c  = colors[i % len(colors)]
        ep = range(1, len(history['train_acc']) + 1)
        axes[0].plot(ep, history['train_acc'], '--', color=c, alpha=0.6, label=f'{name} (train)')
        axes[0].plot(ep, history['val_acc'],   '-',  color=c, linewidth=2, label=f'{name} (val)')
        axes[1].plot(ep, history['train_loss'], '-', color=c, linewidth=2, label=name)
    axes[0].set_title('Training vs Validation Accuracy', fontsize=14, fontweight='bold')
    axes[0].set_xlabel('Epoch'); axes[0].set_ylabel('Accuracy (%)')
    axes[0].legend(); axes[0].grid(alpha=0.3)
    axes[1].set_title('Training Loss', fontsize=14, fontweight='bold')
    axes[1].set_xlabel('Epoch'); axes[1].set_ylabel('Loss')
    axes[1].legend(); axes[1].grid(alpha=0.3)
    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches='tight')
    plt.show()
    print(f'Curves saved: {save_path}')


def plot_confusion_matrix(y_true, y_pred, class_names, save_path='confusion_matrix.png'):
    cm      = confusion_matrix(y_true, y_pred)
    cm_norm = cm.astype('float') / cm.sum(axis=1)[:, np.newaxis]
    fig, ax = plt.subplots(figsize=(20, 18))
    sns.heatmap(cm_norm, annot=False, cmap='Blues',
                xticklabels=class_names, yticklabels=class_names, ax=ax)
    ax.set_title('Normalized Confusion Matrix — Full Fusion Model',
                 fontsize=16, fontweight='bold')
    ax.set_xlabel('Predicted'); ax.set_ylabel('True')
    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches='tight')
    plt.show()
    print(f'Confusion matrix saved: {save_path}')


