# ── Single-sample pipeline figure ────────────────────────────────────────────

def run_pipeline(model, image_path, coords_tensor, encoder,
                 true_class=None, save_path='pipeline_single_demo.png'):
    """
    Four-panel figure: Input image → Hand keypoints → Model output → Braille cell.
    """
    img_raw  = PILImage.open(image_path).convert('RGB')
    img_t    = EVAL_TF(img_raw).unsqueeze(0).to(device)
    coords_t = coords_tensor.unsqueeze(0).to(device)

    model.eval()
    with torch.no_grad():
        logits   = model(img_t, coords_t)
        probs    = torch.softmax(logits, dim=1)
        pred_enc = logits.argmax(1).item()

    pred_cls   = int(encoder.inverse_transform([pred_enc])[0])
    confidence = probs[0, pred_enc].item() * 100
    if true_class is None:
        true_class = pred_cls

    correct  = pred_cls == true_class
    suptitle = ('Correctly classified' if correct else 'Incorrectly classified')
    sc       = C_CORRECT if correct else C_INCORRECT

    fig = plt.figure(figsize=(19, 5.8), facecolor=C_BG)
    fig.patch.set_facecolor(C_BG)
    gs  = GridSpec(1, 4, figure=fig,
                   width_ratios=[2.1, 2.0, 2.5, 1.9],
                   wspace=0.10,
                   left=0.03, right=0.97,
                   top=0.83,  bottom=0.09)

    # ── Panel 1: image ────────────────────────────────────────────────────────
    ax_img = fig.add_subplot(gs[0, 0])
    ax_img.imshow(img_raw)
    ax_img.set_title('① Input RGB image', fontsize=9, pad=5, color=C_TEXT)
    for sp in ax_img.spines.values():
        sp.set_edgecolor('#CCCCCC'); sp.set_linewidth(0.7)
    ax_img.tick_params(labelsize=6, colors='#BBB')
    te = BDSL47_BRAILLE[true_class]
    ax_img.set_xlabel(
        f'True sign: {te["name"]}  (class {true_class})',
        fontsize=7.5, color=C_ALPHA, labelpad=4
    )

    # ── Panel 2: hand skeleton ────────────────────────────────────────────────
    ax_hand = fig.add_subplot(gs[0, 1])
    _draw_hand_panel(ax_hand, coords_tensor)

    # ── Panel 3: model output ─────────────────────────────────────────────────
    ax_out = fig.add_subplot(gs[0, 2])
    _draw_output_panel(ax_out, pred_cls, confidence, true_class)

    # ── Panel 4: Braille ──────────────────────────────────────────────────────
    ax_br = fig.add_subplot(gs[0, 3])
    _draw_braille_panel(ax_br, pred_cls)

    # Inter-panel arrows
    for xf in [0.255, 0.490, 0.730]:
        _panel_arrow(fig, xf)

    fig.suptitle(
        f'End-to-end pipeline: BdSL sign  →  Bangladeshi Braille  [{suptitle}]\n'
        f'GVF-Net: Improved GCN + EfficientNet-B0  ·  User-independent evaluation  ·  '
        f'Braille ref: Hossain et al. 2013 + Ahmed et al. 2025  ·  All 47 patterns verified',
        fontsize=9.5, color=sc, y=0.97
    )
    plt.savefig(save_path, dpi=160, bbox_inches='tight', facecolor=C_BG)
    plt.show()
    print(f'Saved: {save_path}')

    braille_str, _ = class_to_braille(pred_cls)
    return pred_cls, braille_str, BDSL47_BRAILLE[pred_cls]


# ── Batch demo ───────────────────────────────────────────────────────────────

def batch_pipeline_demo(model, test_samples, encoder,
                        n_samples=12,
                        save_path='pipeline_batch_demo.png'):
    """
    Grid of n_samples unique classes.  Each tile: image left + Braille cell right.
    Green border = correct, red = incorrect.
    """
    random.seed(42)
    seen, selected = set(), []
    for s in random.sample(test_samples, len(test_samples)):
        cls = int(s['label'])
        if cls not in seen:
            selected.append(s); seen.add(cls)
        if len(selected) >= n_samples:
            break

    ncols    = 4
    nrows    = (len(selected) + ncols - 1) // ncols
    fig_w    = ncols * 5.8
    fig_h    = nrows * 5.4 + 1.0

    fig = plt.figure(figsize=(fig_w, fig_h), facecolor=C_BG)
    fig.patch.set_facecolor(C_BG)

    gs_outer = mgridspec.GridSpec(
        nrows, ncols,
        hspace=0.52, wspace=0.38,
        left=0.02, right=0.98,
        top=0.91,  bottom=0.02
    )

    model.eval()
    correct_count = 0

    for i, s in enumerate(selected):
        row, col = i // ncols, i % ncols
        gs_in = GridSpecFromSubplotSpec(
            2, 2,
            subplot_spec=gs_outer[row, col],
            height_ratios=[3.2, 1.0],
            width_ratios=[1.05, 0.95],
            hspace=0.06, wspace=0.18
        )
        ax_img  = fig.add_subplot(gs_in[0, 0])
        ax_cell = fig.add_subplot(gs_in[0, 1])
        ax_info = fig.add_subplot(gs_in[1, :])

        true_cls  = int(s['label'])
        img_raw   = PILImage.open(s['img_path']).convert('RGB')
        img_t     = EVAL_TF(img_raw).unsqueeze(0).to(device)
        coords_t  = torch.tensor(s['coords']).unsqueeze(0).to(device)

        with torch.no_grad():
            pred_enc = model(img_t, coords_t).argmax(1).item()
        pred_cls  = int(encoder.inverse_transform([pred_enc])[0])
        correct   = pred_cls == true_cls
        if correct: correct_count += 1

        e   = BDSL47_BRAILLE[pred_cls]
        te  = BDSL47_BRAILLE[true_cls]
        bc  = C_CORRECT if correct else C_INCORRECT
        sym = '✓' if correct else '✗'

        # Image
        ax_img.imshow(img_raw)
        ax_img.axis('off')
        for sp in ax_img.spines.values():
            sp.set_visible(True); sp.set_edgecolor(bc); sp.set_linewidth(2.8)
        ax_img.set_title(
            f'Pred: {e["name"]}  {sym}',
            fontsize=8, color=bc, pad=3, fontweight='bold'
        )

        # Braille cell
        is_digit = e['type'] == 'digit'
        dc = C_DIGIT if is_digit else C_ALPHA
        de = C_DIGIT_E if is_digit else C_ALPHA_E
        mask = e['mask']

        ax_cell.set_xlim(0, 1); ax_cell.set_ylim(0, 1)
        ax_cell.set_aspect('equal'); ax_cell.axis('off')

        tag  = 'DIGIT' if is_digit else 'ALPHA'
        lbl  = '2-cell' if is_digit else '1-cell'
        tc   = C_DIGIT if is_digit else C_ALPHA

        ax_cell.text(0.5, 0.98,
                     f'Class {pred_cls}: {e["name"]}  [{lbl}]',
                     ha='center', va='top', fontsize=6.5,
                     color=tc, fontweight='bold',
                     transform=ax_cell.transAxes)

        S = 0.78
        cw = _cell_width(S)
        if is_digit:
            _draw_bordered_cell(ax_cell, NS_MASK, C_NS, C_ALPHA_E,
                                0.02, 0.10, S)
            _draw_bordered_cell(ax_cell, mask,    dc,   de,
                                0.02 + cw + 0.04, 0.10, S)
        else:
            xo = (1.0 - cw) / 2
            _draw_bordered_cell(ax_cell, mask, dc, de, xo, 0.10, S)

        braille_str, _ = class_to_braille(pred_cls)
        active = ', '.join(str(k+1) for k in range(6) if (mask>>k)&1) or '—'
        uc_str = (f"U+283C·U+{0x2800+mask:04X}" if is_digit
                  else f"U+{0x2800+mask:04X}")

        # Info strip
        ax_info.axis('off')
        ax_info.text(0.5, 0.92,
                     f'True: {te["name"]}  (class {true_cls})',
                     ha='center', va='top', fontsize=6.5, color=C_MUTED,
                     transform=ax_info.transAxes)
        ax_info.text(0.5, 0.46,
                     f"{e['sign']}  ↳ {uc_str}   Dots: {active}",
                     ha='center', va='top', fontsize=6.0,
                     color=C_TEXT, fontfamily='monospace',
                     transform=ax_info.transAxes)

    demo_acc = 100. * correct_count / len(selected)

    legend_els = [
        mpatches.Patch(facecolor=C_CORRECT,   edgecolor=C_CORRECT,
                       label=f'Correct  ({correct_count}/{len(selected)})'),
        mpatches.Patch(facecolor=C_INCORRECT, edgecolor=C_INCORRECT,
                       label='Incorrect'),
        mpatches.Patch(facecolor=C_ALPHA,     edgecolor=C_ALPHA_E,
                       label='Alphabet dot'),
        mpatches.Patch(facecolor=C_DIGIT,     edgecolor=C_DIGIT_E,
                       label='Digit dot'),
    ]
    fig.legend(handles=legend_els, loc='upper right',
               fontsize=7.5, framealpha=0.95,
               bbox_to_anchor=(0.99, 0.995))

    fig.suptitle(
        f'Batch pipeline demo: BdSL sign  →  Bangladeshi Braille  ·  GVF-Net\n'
        f'Demo accuracy: {demo_acc:.0f}%  ·  '
        f'Green border = correct   ·   Red border = incorrect  ·  '
        f'Left: input image   ·   Right: predicted Braille cell\n'
        f'Ref: Hossain et al. 2013 + Ahmed et al. 2025  ·  All 47 patterns verified',
        fontsize=9.5, color=C_TEXT, y=0.995
    )
    plt.savefig(save_path, dpi=150, bbox_inches='tight', facecolor=C_BG)
    plt.show()
    print(f'Saved: {save_path}')


