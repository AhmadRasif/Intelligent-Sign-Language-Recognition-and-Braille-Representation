def collect_multimodal_data(root_dir, target_users):
    root_path = Path(root_dir)
    samples = []
    all_csvs = [p for p in root_path.rglob('*') if p.suffix.lower() == '.csv']
    print(f'Scanning users {target_users} | {len(all_csvs)} CSVs found...')
    for csv_path in all_csvs:
        path_str = str(csv_path).lower()
        is_target = any(
            f'user {uid}' in path_str or f'user_{uid}' in path_str or
            f'user{uid:02d}' in path_str or f'user {uid:02d}' in path_str
            for uid in target_users
        )
        if not is_target:
            continue
        sign_dir  = csv_path.parent
        img_dirs  = [d for d in sign_dir.iterdir()
                     if d.is_dir() and ('image' in d.name.lower() or 'sign' in d.name.lower())]
        if not img_dirs:
            continue
        img_dir = img_dirs[0]
        available = {}
        for f in img_dir.glob('*'):
            if f.suffix.lower() in ['.jpg','.jpeg','.png','.webp']:
                m = re.search(r'\((\d+)\)', f.name) or re.search(r'(\d+)', f.name)
                if m:
                    available[m.group(1)] = f
        try:
            df = pd.read_csv(csv_path)
            for _, row in df.iterrows():
                raw   = str(row.iloc[0]).strip()
                fname = raw.replace('\\\\','/').replace('//','/')\
                           .replace('\\','/').split('/')[-1]
                img_path = img_dir / fname
                if not img_path.exists():
                    m2 = re.search(r'\((\d+)\)', fname) or re.search(r'(\d+)', fname)
                    if m2 and m2.group(1) in available:
                        img_path = available[m2.group(1)]
                if img_path and img_path.exists():
                    coords = row.iloc[1:64].values.astype(np.float32).reshape(21,3)
                    label  = str(row.iloc[-1]).strip()
                    if 'sign digits' in path_str:
                        label = str(int(float(label)) + 37)
                    samples.append({'img_path': str(img_path),
                                    'coords': coords, 'label': label})
        except Exception as e:
            print(f'  Warning: {csv_path.name} — {e}')
    print(f'  -> {len(samples)} samples')
    return samples

