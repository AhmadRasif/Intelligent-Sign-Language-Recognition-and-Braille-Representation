class BdSLMultimodalDataset(Dataset):
    def __init__(self, samples, transform=None, encoder=None):
        self.samples   = samples
        self.transform = transform
        self.encoder   = encoder

    def __len__(self): return len(self.samples)

    def __getitem__(self, idx):
        s      = self.samples[idx]
        image  = Image.open(s['img_path']).convert('RGB')
        if self.transform:
            image = self.transform(image)
        coords = torch.tensor(s['coords'], dtype=torch.float32)
        if self.encoder:
            label_idx = self.encoder.transform([s['label']])[0]
            return image, coords, torch.tensor(label_idx, dtype=torch.long)
        return image, coords, s['label']


