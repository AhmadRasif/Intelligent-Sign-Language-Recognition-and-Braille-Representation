# CELL 6: Architecture
#
# A) ViTAttentionBlock   — global self-attention on EfficientNet tokens
# B) ImprovedGeometricStream (GCN)
#      FIX 1: LayerNorm(out_features) replaces BatchNorm1d(21)
#             Normalises learned feature channels per landmark node.
#      FIX 2: 3 layers + residual connections
#             Layer 1: 3->64   no residual
#             Layer 2: 64->128 projection residual
#             Layer 3: 128->128 identity residual
# C) CrossModalAttentionFusion
#      GCN embedding = Query
#      Visual tokens = Key / Value
# ============================================================

# -----------------------------------------------------------
# A) ViTAttentionBlock
# -----------------------------------------------------------
class ViTAttentionBlock(nn.Module):
    def __init__(self, dim, num_heads, mlp_ratio=4, dropout=0.1):
        super().__init__()
        self.norm1 = nn.LayerNorm(dim)
        self.attn  = nn.MultiheadAttention(
            embed_dim=dim, num_heads=num_heads,
            dropout=dropout, batch_first=True
        )
        self.norm2 = nn.LayerNorm(dim)
        self.mlp   = nn.Sequential(
            nn.Linear(dim, mlp_ratio * dim), nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(mlp_ratio * dim, dim), nn.Dropout(dropout)
        )

    def forward(self, x):
        normed = self.norm1(x)
        attn_out, _ = self.attn(normed, normed, normed)
        x = x + attn_out
        x = x + self.mlp(self.norm2(x))
        return x


# -----------------------------------------------------------
# Visual Stream: EfficientNet-B0 + ViTAttentionBlock
# -----------------------------------------------------------
class VisualStream(nn.Module):
    def __init__(self, out_dim=256):
        super().__init__()
        efficientnet  = models.efficientnet_b0(weights='DEFAULT')
        self.backbone = efficientnet.features
        self.adapter  = nn.Conv2d(1280, out_dim, kernel_size=1)
        self.transformer = ViTAttentionBlock(dim=out_dim, num_heads=8, dropout=0.1)
        self.pool     = nn.AdaptiveAvgPool2d(1)
        self.proj     = nn.Linear(out_dim, out_dim)

    def forward(self, x):
        x = self.backbone(x)                            # (B,1280,7,7)
        x = self.adapter(x)                             # (B,256,7,7)
        B, C, H, W = x.shape
        tokens = x.view(B, C, H*W).permute(0, 2, 1)   # (B,49,256)
        tokens = self.transformer(tokens)
        visual_tokens = tokens
        visual_embed  = self.pool(
            tokens.permute(0,2,1).view(B, C, H, W)
        ).flatten(1)
        visual_embed  = self.proj(visual_embed)         # (B,256)
        return visual_tokens, visual_embed


# -----------------------------------------------------------
# B) Improved GCN
# -----------------------------------------------------------
class GraphConvLayer(nn.Module):
    """
    FIX 1: LayerNorm(out_features) — correct normalisation axis.
    Normalises learned feature channels per landmark independently.
    """
    def __init__(self, in_features, out_features):
        super().__init__()
        self.linear = nn.Linear(in_features, out_features, bias=False)
        self.norm   = nn.LayerNorm(out_features)
        self.bias   = nn.Parameter(torch.zeros(out_features))

    def forward(self, x, adj):
        support = self.linear(x)
        out     = torch.matmul(adj, support) + self.bias
        return self.norm(out)


class ImprovedGeometricStream(nn.Module):
    """
    FIX 2: 3-layer GCN with residual connections.
    Layer 1: 3->64   (no residual — input dim too small)
    Layer 2: 64->128 (projection residual: 64->128)
    Layer 3: 128->128 (identity residual)
    """
    def __init__(self, adj_matrix, out_dim=256):
        super().__init__()
        self.register_buffer('adj', adj_matrix)
        self.gcn1 = GraphConvLayer(3,   64)
        self.gcn2 = GraphConvLayer(64,  128)
        self.gcn3 = GraphConvLayer(128, 128)
        self.act1 = nn.LeakyReLU(0.2)
        self.act2 = nn.LeakyReLU(0.2)
        self.act3 = nn.LeakyReLU(0.2)
        self.res_proj_1to2 = nn.Linear(64, 128, bias=False)
        self.fc = nn.Sequential(
            nn.Linear(21 * 128, 512),
            nn.LeakyReLU(0.2),
            nn.Dropout(0.3),
            nn.Linear(512, out_dim)
        )

    def forward(self, x):
        x1 = self.act1(self.gcn1(x,  self.adj))
        x2 = self.act2(self.gcn2(x1, self.adj) + self.res_proj_1to2(x1))
        x3 = self.act3(self.gcn3(x2, self.adj) + x2)
        x3 = x3.view(x3.size(0), -1)
        return self.fc(x3)


# -----------------------------------------------------------
# C) Cross-Modal Attention Fusion
# GCN embedding = Query | Visual tokens = Key / Value
# -----------------------------------------------------------
class CrossModalAttentionFusion(nn.Module):
    def __init__(self, dim=256, num_heads=8, dropout=0.1):
        super().__init__()
        self.norm_q     = nn.LayerNorm(dim)
        self.norm_kv    = nn.LayerNorm(dim)
        self.cross_attn = nn.MultiheadAttention(
            embed_dim=dim, num_heads=num_heads,
            dropout=dropout, batch_first=True
        )
        self.norm_out = nn.LayerNorm(dim)
        self.ffn = nn.Sequential(
            nn.Linear(dim, dim*2), nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(dim*2, dim)
        )

    def forward(self, geo_embed, visual_tokens):
        q  = self.norm_q(geo_embed.unsqueeze(1))
        kv = self.norm_kv(visual_tokens)
        attended, _ = self.cross_attn(q, kv, kv)
        attended = attended.squeeze(1)
        attended = attended + self.ffn(self.norm_out(attended))
        return torch.cat([geo_embed, attended], dim=1)


# -----------------------------------------------------------
# Full Model + Ablation Models
# -----------------------------------------------------------
class MultimodalFusionModel(nn.Module):
    def __init__(self, adj_matrix, num_classes=47):
        super().__init__()
        self.visual_stream    = VisualStream(out_dim=256)
        self.geometric_stream = ImprovedGeometricStream(adj_matrix, out_dim=256)
        self.fusion           = CrossModalAttentionFusion(dim=256, num_heads=8)
        self.classifier       = nn.Sequential(
            nn.Linear(512, 256), nn.GELU(), nn.Dropout(0.3),
            nn.Linear(256, 128), nn.GELU(), nn.Dropout(0.2),
            nn.Linear(128, num_classes)
        )

    def forward(self, img, coords):
        visual_tokens, _ = self.visual_stream(img)
        geo_embed        = self.geometric_stream(coords)
        fused            = self.fusion(geo_embed, visual_tokens)
        return self.classifier(fused)


class GCNOnlyModel(nn.Module):
    def __init__(self, adj_matrix, num_classes=47):
        super().__init__()
        self.geometric_stream = ImprovedGeometricStream(adj_matrix, out_dim=256)
        self.classifier = nn.Sequential(
            nn.Linear(256, 128), nn.GELU(), nn.Dropout(0.3),
            nn.Linear(128, num_classes)
        )
    def forward(self, img, coords):
        return self.classifier(self.geometric_stream(coords))


class VisualOnlyModel(nn.Module):
    def __init__(self, num_classes=47):
        super().__init__()
        self.visual_stream = VisualStream(out_dim=256)
        self.classifier    = nn.Sequential(
            nn.Linear(256, 128), nn.GELU(), nn.Dropout(0.3),
            nn.Linear(128, num_classes)
        )
    def forward(self, img, coords):
        _, visual_embed = self.visual_stream(img)
        return self.classifier(visual_embed)


