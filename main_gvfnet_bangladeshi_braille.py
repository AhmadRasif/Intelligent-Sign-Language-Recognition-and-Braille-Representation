# ── Utilities ─────────────────────────────────────────────────────────────────

def get_dot_pattern(mask):
    return [(mask >> i) & 1 for i in range(6)]

def class_to_braille(cls):
    e  = BDSL47_BRAILLE[cls]
    uc = chr(0x2800 + e['mask'])
    return (chr(0x2800 + NS_MASK) + uc, e) if e['type']=='digit' else (uc, e)

def sign_sequence_to_braille(seq):
    out, in_run = '', False
    for cls in seq:
        e  = BDSL47_BRAILLE[cls]
        uc = chr(0x2800 + e['mask'])
        if e['type'] == 'digit':
            if not in_run: out += chr(0x2800 + NS_MASK); in_run = True
        else:
            in_run = False
        out += uc
    return out


