C_CORRECT   = '#1A6B3A'
C_INCORRECT = '#A32D2D'
C_INFO_BG   = '#F0F4F8'
C_ARROW     = '#8096A8'


EVAL_TF = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
])

FINGER_EDGES = {
    'Thumb':  [(0,1),(1,2),(2,3),(3,4)],
    'Index':  [(0,5),(5,6),(6,7),(7,8)],
    'Middle': [(0,9),(9,10),(10,11),(11,12)],
    'Ring':   [(0,13),(13,14),(14,15),(15,16)],
    'Pinky':  [(0,17),(17,18),(18,19),(19,20)],
}
FINGER_COLORS = {
    'Thumb':'#E53935','Index':'#1E88E5','Middle':'#43A047',
    'Ring':'#FB8C00','Pinky':'#8E24AA',
}
TIP_LABELS = {4:'T', 8:'I', 12:'M', 16:'R', 20:'P'}


def _panel_arrow(fig, x, y=0.46):
    """Draw a thin centred arrow between panels."""
    fig.text(x, y, '→', ha='center', va='center',
             fontsize=18, color=C_ARROW,
             transform=fig.transFigure)


def _draw_hand_panel(ax, coords):
    """
    Coloured hand skeleton with fingertip labels, wrist highlight,
    and z-depth annotation. Pixel coords from depth sensor → y-axis flipped.
    """
    cn = coords.numpy() if hasattr(coords, 'numpy') else np.array(coords)
    xs, ys = cn[:, 0], cn[:, 1]
    z_lo, z_hi = cn[:, 2].min(), cn[:, 2].max()

    for finger, edges in FINGER_EDGES.items():
        fc = FINGER_COLORS[finger]
        for s, t in edges:
            ax.plot([xs[s], xs[t]], [ys[s], ys[t]], '-',
                    color=fc, lw=2.0, alpha=0.88, zorder=2)

    ax.scatter(xs, ys, c='#37474F', s=22, zorder=4, linewidths=0)
    ax.scatter(xs[0], ys[0], c='#FFD600', s=55, zorder=5,
               edgecolors='#333333', linewidths=0.8)
    ax.text(xs[0], ys[0], ' 0', ha='left', va='center',
            fontsize=6, color='#333')

    for tip, lbl in TIP_LABELS.items():
        ax.text(xs[tip], ys[tip], f' {lbl}', ha='left', va='center',
                fontsize=6.5, color='#2C3E50', fontweight='bold')

    ax.invert_yaxis()
    ax.set_title(
        f'② Hand keypoints (x, y)  ·  21 landmarks\n'
        f'z-depth range: [{z_lo:.3f}, {z_hi:.3f}]',
        fontsize=8, pad=5, color=C_TEXT
    )
    ax.set_xlabel('x', fontsize=7, color=C_MUTED, labelpad=2)
    ax.set_ylabel('y', fontsize=7, color=C_MUTED, labelpad=2)
    ax.tick_params(labelsize=6, colors='#AAA')
    for sp in ax.spines.values():
        sp.set_edgecolor('#DDDDDD'); sp.set_linewidth(0.5)

    legend_els = ([plt.Line2D([0],[0], color=FINGER_COLORS[f], lw=2, label=f)
                   for f in FINGER_EDGES]
                  + [plt.Line2D([0],[0], marker='o', color='w',
                                markerfacecolor='#FFD600', markersize=7,
                                markeredgecolor='#333', mew=0.7,
                                label='Wrist (0)')])
    ax.legend(handles=legend_els, fontsize=6, loc='lower right',
              framealpha=0.9, handlelength=1.0)


def _draw_output_panel(ax, pred_cls, confidence, true_cls):
    """
    Model output info box: confidence bar, field table.
    """
    ax.set_xlim(0, 1); ax.set_ylim(0, 1); ax.axis('off')
    e        = BDSL47_BRAILLE[pred_cls]
    te       = BDSL47_BRAILLE[true_cls]
    is_digit = e['type'] == 'digit'
    mask     = e['mask']
    active   = ', '.join(str(i+1) for i in range(6) if (mask>>i)&1) or '—'
    uc_str   = (f"U+283C · U+{0x2800+mask:04X}" if is_digit
                else f"U+{0x2800+mask:04X}")
    correct  = pred_cls == true_cls
    rc       = C_CORRECT if correct else C_INCORRECT
    cell_lbl = '2-cell (NS + digit)' if is_digit else '1-cell (letter)'
    type_lbl = 'Digit sign' if is_digit else 'Alphabet sign'
    braille_str, _ = class_to_braille(pred_cls)

    # Header bar
    ax.add_patch(mpatches.FancyBboxPatch(
        (0.02, 0.90), 0.96, 0.085,
        boxstyle='round,pad=0.01',
        facecolor=C_CORRECT, edgecolor='none', zorder=2
    ))
    ax.text(0.50, 0.943, '③  Model output',
            ha='center', va='center', fontsize=9,
            fontweight='bold', color='white', zorder=3,
            transform=ax.transAxes)

    # Confidence bar
    ax.add_patch(mpatches.FancyBboxPatch(
        (0.02, 0.80), 0.96, 0.07,
        boxstyle='round,pad=0.005',
        facecolor='#DDE5EE', edgecolor='none', zorder=1
    ))
    ax.add_patch(mpatches.FancyBboxPatch(
        (0.02, 0.80), 0.96*(confidence/100), 0.07,
        boxstyle='round,pad=0.005',
        facecolor=C_CORRECT, edgecolor='none', zorder=2
    ))
    ax.text(0.50, 0.835, f'Confidence: {confidence:.1f}%',
            ha='center', va='center', fontsize=8,
            fontweight='bold', color='white', zorder=3,
            transform=ax.transAxes)

    # Outer border
    ax.add_patch(mpatches.FancyBboxPatch(
        (0.01, 0.01), 0.98, 0.97,
        boxstyle='round,pad=0.01',
        linewidth=0.8, edgecolor='#C8D4E0',
        facecolor=C_INFO_BG, zorder=0
    ))

    # Field rows
    fields = [
        ('Predicted class', f'{pred_cls}',          C_ALPHA),
        ('Sign name',       e['name'],               C_ALPHA),
        ('Sign symbol',     e['sign'],               C_TEXT),
        ('Type',            type_lbl,                C_TEXT),
        ('Confidence',      f'{confidence:.1f}%',    C_TEXT),
        ('True class',      f'{true_cls} — {te["name"]}', C_TEXT),
        ('Result',          'Correct ✓' if correct else 'Incorrect ✗', rc),
        (None, None, None),
        ('Braille type',    cell_lbl,                C_TEXT),
        ('Braille char',    braille_str,             C_TEXT),
        ('Unicode',         uc_str,                  C_ALPHA),
        ('Active dots',     active,                  C_ALPHA),
        ('Bitmask',         f'{mask:06b}',           C_MUTED),
    ]
    y = 0.77
    for label, val, col in fields:
        if label is None:
            y -= 0.020; continue
        ax.text(0.06, y, label + ':',
                ha='left', va='top', fontsize=7.2, color=C_MUTED,
                transform=ax.transAxes)
        ax.text(0.46, y, str(val),
                ha='left', va='top', fontsize=7.2, color=col,
                fontweight='bold', transform=ax.transAxes)
        y -= 0.059


